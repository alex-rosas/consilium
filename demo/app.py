RISK_COLORS = {
    "High":   ("#ef4444", "#450a0a", "#fca5a5"),   # bg, card-bg, text
    "Medium": ("#f59e0b", "#431407", "#fcd34d"),
    "Low":    ("#22c55e", "#052e16", "#86efac"),
    "N/A":    ("#64748b", "#1e293b", "#94a3b8"),
}

RISK_EMOJI = {"High": "🔴", "Medium": "🟡", "Low": "🟢", "N/A": "⚪"}

CATEGORY_COLORS = {
    "Revenue":     "#6366f1",
    "Audit":       "#f59e0b",
    "Risk":        "#ef4444",
    "Edge":        "#8b5cf6",
    "Cross-Std":   "#06b6d4",
    "Adjacent":    "#10b981",
    "Improvement": "#84cc16",
}


def risk_badge(level: str) -> str:
    emoji = RISK_EMOJI.get(level, "⚪")
    return f"{emoji} **{level}**"


def render_finding_card(finding: dict, index: int) -> None:
    level = finding.get("risk_level", "N/A")
    border, _, _ = RISK_COLORS.get(level, RISK_COLORS["N/A"])
    emoji = RISK_EMOJI.get(level, "⚪")
    clause = finding.get("clause_reference", "—")
    text = finding.get("finding", "")
    source = finding.get("document_source", "")

    with st.container():
        st.markdown(
            f"""
            <div style="
                border-left: 4px solid {border};
                background: #1e293b;
                border-radius: 8px;
                padding: 0.8rem 1rem;
                margin-bottom: 0.5rem;
            ">
                <div style="display:flex; align-items:center; gap:0.5rem; margin-bottom:0.3rem;">
                    <span style="font-weight:700; color:#cbd5e1;">{clause}</span>
                    <span style="font-size:0.75rem; font-weight:700; background:{border}22;
                        color:{border}; border:1px solid {border}44;
                        padding:0.1rem 0.5rem; border-radius:4px;">{emoji} {level}</span>
                    <span style="font-size:0.72rem; color:#475569; margin-left:auto;">{source}</span>
                </div>
                <div style="color:#94a3b8; font-size:0.88rem; line-height:1.5;">{text}</div>
            </div>
            """,
            unsafe_allow_html=True,
        )


