with tab1:
    st.markdown("### Submit a compliance query")
    st.caption(
        "Select one of the pre-loaded queries or type your own (demo will match the closest pre-recorded response). "
        "The streaming sequence below mirrors exactly what you'd see in the live browser UI at `localhost:8001`."
    )

    query_labels = {c["label"]: c for c in DEMO_CASES}
    selected_label = st.selectbox(
        "Query",
        options=list(query_labels.keys()),
        index=0,
        label_visibility="collapsed",
    )
    case = query_labels[selected_label]

    st.markdown(
        f"""
        <div style="background:#1e293b; border:1px solid #334155; border-radius:8px;
            padding:0.75rem 1rem; margin:0.5rem 0 1rem 0; font-size:0.9rem; color:#e2e8f0;">
            {case['query']}
        </div>
        """,
        unsafe_allow_html=True,
    )

    col_btn, col_info = st.columns([1, 4])
    with col_btn:
        run = st.button("▶  Analyze", type="primary", use_container_width=True)
    with col_info:
        st.caption(
            f"Category: **{case['category']}** · "
            f"Recorded latency: **{case['latency_ms']}ms** · "
            f"Confidence: **{case['confidence']}**"
        )

    if run:
        st.divider()

        # -- Planner phase --
        with st.status("🗂️  Planner agent running…", expanded=True) as planner_status:
            time.sleep(0.6)
            st.write("Decomposing query into analysis tasks…")
            time.sleep(0.7)
            for i, task in enumerate(case["task_plan"], 1):
                st.write(f"  ✓ Task {i}: {task}")
                time.sleep(0.3)
            planner_status.update(
                label=f"✅ Planner complete — {len(case['task_plan'])} tasks planned (confidence 0.85)",
                state="complete",
            )

        # -- Analyst phase --
        findings = case["findings"]
        non_na = [f for f in findings if f["risk_level"] != "N/A"]
        high_count = sum(1 for f in findings if f["risk_level"] == "High")
        medium_count = sum(1 for f in findings if f["risk_level"] == "Medium")

        st.markdown("#### 🔍 Analyst Findings")
        findings_placeholder = st.empty()
        shown = []

        with st.status("🔍  Analyst agent running…", expanded=False) as analyst_status:
            for i, finding in enumerate(findings):
                time.sleep(0.55)
                shown.append(finding)
                with findings_placeholder.container():
                    for f in shown:
                        render_finding_card(f, findings.index(f))
            analyst_status.update(
                label=f"✅ Analyst complete — {len(findings)} findings · "
                      f"{high_count} High · {medium_count} Medium (confidence 0.85)",
                state="complete",
            )

        # -- Synthesizer phase --
        with st.status("📝  Synthesizer agent running…", expanded=False) as synth_status:
            time.sleep(1.1)
            synth_status.update(label="✅ Report synthesized", state="complete")

        st.markdown("#### 📄 Compliance Report")
        with st.expander("View full report", expanded=True):
            st.markdown(case["report"])

        # -- Done --
        st.success(
            "✅ **Pipeline complete** — All 3 agents finished. "
            "In the live system, a Phoenix trace link would appear here for distributed trace inspection.",
            icon="⚖️",
        )

        # Risk summary chips
        st.markdown("**Risk summary:**")
        chip_cols = st.columns(4)
        counts = {lvl: sum(1 for f in findings if f["risk_level"] == lvl)
                  for lvl in ["High", "Medium", "Low", "N/A"]}
        for col, (lvl, count) in zip(chip_cols, counts.items()):
            border, bg, text = RISK_COLORS[lvl]
            col.markdown(
                f"""
                <div style="background:{bg}; border:1px solid {border}44; border-radius:8px;
                    padding:0.6rem; text-align:center;">
                    <div style="font-size:1.4rem; font-weight:800; color:{border};">{count}</div>
                    <div style="font-size:0.75rem; color:{text};">{lvl} risk</div>
                </div>
                """,
                unsafe_allow_html=True,
            )


