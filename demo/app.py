    if run2:
        findings2 = case2["findings"]

        # Stage 1 — FastAPI receives request
        st.markdown("---")
        col_api, col_sse = st.columns([3, 2])

        with col_api:
            with st.expander("**① FastAPI** — Request received", expanded=True):
                st.json({
                    "endpoint": "POST /workflow/stream",
                    "payload": {"query": case2["query"]},
                    "media_type": "text/event-stream",
                    "retrieval_provider": "mock (demo) / quaestor (live)",
                })

        with col_sse:
            st.markdown("**SSE event stream →**")
            sse_placeholder = st.empty()
            sse_events: list[str] = []

            def update_sse(new_event: str) -> None:
                sse_events.append(new_event)
                sse_placeholder.code("\n".join(sse_events), language="json")

        time.sleep(0.4)

        # Stage 2 — Planner
        st.markdown("---")
        with st.expander("**② PlannerAgent** — Task decomposition", expanded=True):
            time.sleep(0.7)
            pcols = st.columns([1, 1])
            with pcols[0]:
                st.markdown("**Input (WorkflowState)**")
                st.json({"user_query": case2["query"], "retrieved_chunks": ["chunk_1", "…", "chunk_5"]})
            with pcols[1]:
                st.markdown("**Output**")
                task_plan = [
                    {"task_id": f"task_{i+1}", "description": t, "assigned_agent": "analyst", "dependencies": []}
                    for i, t in enumerate(case2["task_plan"])
                ]
                st.json({"task_plan": task_plan, "planner_confidence": 0.85})
            update_sse(f'data: {{"type":"planner_complete","task_count":{len(case2["task_plan"])},"confidence":0.85}}')

        # Stage 3 — Analyst
        st.markdown("---")
        with st.expander("**③ AnalystAgent** — Risk classification", expanded=True):
            time.sleep(0.5)
            acols = st.columns([1, 1])
            with acols[0]:
                st.markdown("**Input**")
                st.json({"task_plan": [t["description"][:50] + "…" for t in task_plan], "retrieved_chunks": 5})
                st.markdown("**Quaestor retrieval →**")
                st.caption("5 document chunks retrieved from JPMorgan Q3 2023 + IFRS/PCAOB standards")

            with acols[1]:
                st.markdown("**Findings (streamed one-by-one)**")
                f_placeholder = st.empty()
                shown2: list[dict] = []
                for f in findings2:
                    time.sleep(0.4)
                    shown2.append(f)
                    f_placeholder.json([
                        {"clause": x["clause_reference"], "risk_level": x["risk_level"]}
                        for x in shown2
                    ])
                    update_sse(
                        f'data: {{"type":"analyst_finding","finding":{{"clause_reference":"{f["clause_reference"]}","risk_level":"{f["risk_level"]}"}}}}'
                    )

            update_sse(f'data: {{"type":"analyst_complete","findings_count":{len(findings2)},"confidence":0.85}}')

        # Stage 4 — Synthesizer
        st.markdown("---")
        with st.expander("**④ SynthesizerAgent** — Report generation", expanded=True):
            time.sleep(0.9)
            scols = st.columns([1, 1])
            with scols[0]:
                st.markdown("**Input**")
                risk_summary = {
                    lvl: sum(1 for f in findings2 if f["risk_level"] == lvl)
                    for lvl in ["High", "Medium", "Low", "N/A"]
                }
                st.json({
                    "risk_findings_count": len(findings2),
                    "risk_summary": risk_summary,
                })
            with scols[1]:
                st.markdown("**Output — Compliance Report**")
                st.markdown(case2["report"][:800] + "\n\n*(truncated — see Tab 1 for full report)*")
            update_sse('data: {"type":"report_complete","report":"## Compliance Assessment Report …"}')
            update_sse('data: {"type":"done","trace_id":null}')

        # Final state summary
        st.markdown("---")
        st.success(
            f"**Pipeline complete.** WorkflowState after all 3 nodes: "
            f"`agent_history = ['planner', 'analyst', 'synthesizer']` · "
            f"`confidence = min(0.85, 0.85, 0.85) = 0.85` · "
            f"`fallback_events = []`"
        )

        # WorkflowState delta visualization
        with st.expander("🔎 Final WorkflowState (full)", expanded=False):
            st.json({
                "user_query": case2["query"],
                "task_plan": [t["description"] for t in task_plan],
                "risk_findings": [
                    {"clause_reference": f["clause_reference"], "risk_level": f["risk_level"]}
                    for f in findings2
                ],
                "final_report": "# Compliance Assessment Report\n…",
                "planner_confidence": 0.85,
                "analyst_confidence": 0.85,
                "synthesizer_confidence": 0.85,
                "agent_history": ["planner", "analyst", "synthesizer"],
                "fallback_events": [],
                "current_agent": "synthesizer",
                "error": None,
            })


